#!/bin/sh
# The stage-5 exit test: the REAL engine completes one full agent turn
# over the pipes protocol, natively AND as a wasm component under
# wasmtime, against the same scripted fake provider.
#
# Self-contained: every toolchain assumption is captured below, so the
# script works against the packaged tina-wasm-host binary from a fresh
# shell. It pins both Dart SDKs by path (a fresh login shell has no
# `dart` on PATH), puts cargo on PATH for the wasm.dart build hooks, and
# materializes the gitignored pubspec_overrides.yaml when it is missing
# — without it the committed pins resolve a wasm_tools too old for the
# edge dart2wasm and the build hooks die. It also clears
# CARGO_TARGET_DIR, which would hide the hook's cargo artifacts, and
# builds the wasm_tools runtime_helpers asset when absent. The runner
# is EMBEDDED-ONLY since the capability merger: there is no --engine
# flag and no positional engine path, so the script builds its own
# tina-wasm-host with the engine compiled in (TINA_WASM_HOST_ENGINE),
# rebuilding whenever the engine component is newer than the binary or
# FORCE_RUNNER_BUILD=1. The default target is this test's own scratch
# directory - the packaged binary elsewhere is never rebuilt. The
# tracked pubspec.lock, rewritten by the override resolution's pub get,
# is restored on exit.
#
# Usage: engine_exit_test.sh
# Tunables (env): RUNNER, ENGINE_WASM, FORCE_ENGINE_BUILD=1, WASM_DART,
#   DART, STABLE_DART, RUNNER_TARGET.
set -e
cd "$(dirname "$0")/.."
PKG="$PWD"

# --- toolchain capture -----------------------------------------------------
# The driver and the engine-component build run on the pinned edge SDK
# (dart2wasm needs branch-tip wasm_tools); the native engine leg runs on
# the box's stable SDK, which a fresh PATH may not even have.
DART="${DART:-$HOME/tools/dart-sdk-src/sdk/out/ReleaseX64/dart-sdk/bin/dart}"
STABLE_DART="${STABLE_DART:-$(command -v dart || true)}"
STABLE_DART="${STABLE_DART:-/opt/dart-sdk/bin/dart}"
WASM_DART="${WASM_DART:-/tmp/codex85-loader-integration-20261108/wasm.dart}"
# This test's own cargo target for the embedded runner. Deliberately NOT
# the packaged binary's target: the rebuild below must never clobber a
# packaged tina-wasm-host.
RUNNER_TARGET="${RUNNER_TARGET:-${TMPDIR:-/tmp}/stage5-runner-target}"
# The wasm_tools build hook expects its cargo artifacts in its own
# workspace root's target/; a global CARGO_TARGET_DIR (the shared target
# the host binary is built in) hides them from the hook and kills the
# build. Clear it here; the runner lookup below uses RUNNER_TARGET.
unset CARGO_TARGET_DIR
# The wasm.dart build hooks compile Rust helpers: cargo must be on PATH.
PATH="$HOME/.cargo/bin:$PATH"
export PATH

ENGINE_WASM="$PKG/bin/engine.wasm"

# --- wasm.dart pin overrides ------------------------------------------------
# The committed pins (wasm_tools @ ec9f801eb) predate the edge dart2wasm's
# timeline implicit import and die in the build hooks; engine builds need
# the branch tip (18f51ea). The override file is gitignored, so a fresh
# clone lacks it: materialize it — path overrides into a local wasm.dart
# checkout when one exists, git refs otherwise. Never clobber an existing
# file; an operator's own override wins.
OVERRIDES="$PKG/pubspec_overrides.yaml"
if [ ! -f "$OVERRIDES" ]; then
  echo "=== writing $OVERRIDES (gitignored; local engine-build pins)"
  if [ -d "$WASM_DART/pkg/wasm_tools" ] && [ -d "$WASM_DART/pkg/wasm_components" ]; then
    cat > "$OVERRIDES" <<EOF
# Generated by tool/engine_exit_test.sh: local engine builds point both
# wasm.dart pins at the checkout whose wasm_tools knows the edge
# dart2wasm's timeline implicit import. Gitignored; CI stays on the
# committed pins. hooks 2.2.0 mirrors the committed pubspec's bridge.
dependency_overrides:
  hooks: 2.2.0
  wasm_components:
    path: $WASM_DART/pkg/wasm_components
  wasm_tools:
    path: $WASM_DART/pkg/wasm_tools
EOF
  else
    cat > "$OVERRIDES" <<'EOF'
# Generated by tool/engine_exit_test.sh: no local wasm.dart checkout, so
# pin both wasm.dart packages to the branch tip over git. Gitignored; CI
# stays on the committed pins. hooks 2.2.0 mirrors the committed bridge.
dependency_overrides:
  hooks: 2.2.0
  wasm_components:
    git:
      url: https://github.com/nmfisher/wasm.dart.git
      path: pkg/wasm_components
      ref: 18f51eaa619d9ab15cf8d0708ebf7c3fbed4c239
  wasm_tools:
    git:
      url: https://github.com/nmfisher/wasm.dart.git
      path: pkg/wasm_tools
      ref: 18f51eaa619d9ab15cf8d0708ebf7c3fbed4c239
EOF
  fi
fi

# The override resolution rewrites the tracked pubspec.lock on pub get;
# snapshot it now (before pub get) and put it back on exit so the tree
# stays clean after the run.
LOCK_BACKUP=/tmp/stage5_pubspec.lock.backup
cp "$PKG/pubspec.lock" "$LOCK_BACKUP"

echo "=== resolving packages (pinned edge SDK)"
( cd "$PKG" && "$DART" pub get )

# The native leg spawns tina_cli on the stable SDK; resolve it when this
# checkout is fresh and has no .dart_tool yet.
if [ ! -f "$PKG/../../.."//apps/tina_cli/.dart_tool/package_config.json ]; then
  echo "=== resolving tina_cli (stable SDK)"
  ( cd "$PKG/../../.."//apps/tina_cli && "$STABLE_DART" pub get )
fi

# --- runner resolution -------------------------------------------------------
# The runner is resolved after the engine component is built (it gets
# embedded into the binary below).


# The runtime_helpers.wasm asset is a nightly-cargo build product, not
# tracked in git and not produced by the pub hooks; the first engine
# build on a fresh machine has to generate it inside the resolved
# wasm_tools package. (Requires jq, cargo+nightly with build-std.)
WASM_TOOLS_ROOT="$(jq -r '.packages[] | select(.name=="wasm_tools") | .rootUri | sub("^file://"; "")' \
  "$PKG/.dart_tool/package_config.json")"
if [ -z "$WASM_TOOLS_ROOT" ]; then
  echo "wasm_tools not found in the package resolution" >&2
  exit 1
fi
if [ ! -f "$WASM_TOOLS_ROOT/assets/runtime_helpers.wasm" ]; then
  echo "=== building runtime_helpers.wasm (nightly cargo, wasm32-unknown-unknown)"
  ( cd "$WASM_TOOLS_ROOT" && ./tool/build_runtime_helpers.sh )
fi

if [ ! -f "$ENGINE_WASM" ] || [ -n "$FORCE_ENGINE_BUILD" ]; then
  echo "=== building the engine component"
  ( cd "$PKG" && "$DART" run wasm_tools compile bin/engine.dart )
fi

# The host is embedded-only: rebuild it with this engine component
# whenever the component is newer than the binary (or on force). The
# explicit RUNNER override skips the build (an operator's own binary).
if [ -z "$RUNNER" ]; then
  if [ ! -x "$RUNNER_TARGET/debug/tina-wasm-host" ] \
      || [ "$ENGINE_WASM" -nt "$RUNNER_TARGET/debug/tina-wasm-host" ] \
      || [ -n "$FORCE_RUNNER_BUILD" ]; then
    echo "=== building the embedded runner (engine newer than the binary, or forced)"
    ( cd "$WASM_DART/pkg/tina_wasm_host" && \
      CARGO_TARGET_DIR="$RUNNER_TARGET" TINA_WASM_HOST_ENGINE="$ENGINE_WASM" \
      cargo build -p tina-wasm-host )
  fi
  RUNNER="$RUNNER_TARGET/debug/tina-wasm-host"
fi
if [ ! -x "$RUNNER" ]; then
  echo "no tina-wasm-host binary found; set RUNNER= or build one:" >&2
  echo "  TINA_WASM_HOST_ENGINE=<engine.wasm> cargo build -p tina-wasm-host  # in the wasm.dart checkout" >&2
  exit 1
fi

echo "=== runner: $RUNNER (embedded engine)"

echo "=== starting the scripted provider"
python3 "$PKG/tool/fake_anthropic_turn_server.py" &
SERVER_PID=$!
trap 'kill $SERVER_PID 2>/dev/null || true; mv "$LOCK_BACKUP" "$PKG/pubspec.lock" 2>/dev/null || true' EXIT
sleep 1

WS_NATIVE=/tmp/stage5-ws-native
WS_WASM=/tmp/stage5-ws-wasm
CFG=/tmp/stage5-config
rm -rf "$WS_NATIVE" "$WS_WASM" "$CFG"
mkdir -p "$WS_NATIVE" "$WS_WASM" "$CFG"
cat > "$CFG/config" <<'EOF'
version = 1

[default]
model = "anthropic/claude-sonnet-4-6"

[plugins]
enabled = [
  "tina/system-instruction",
  "tina/providers",
  "tina/mode",
  "tina/tools",
  "tina/approvals-stream",
  "tina/session-controls",
]
EOF

echo "=== native engine (dart run bin/tina.dart --pipes)"
NATIVE_OUT=/tmp/stage5_native.txt
TINA_LLM_ENDPOINT=http://127.0.0.1:8731 TINA_LLM_TOKEN=stage5-token \
  "$DART" run --enable-asserts "$PKG/tool/pipes_drive.dart" \
  --workspace "$WS_NATIVE" -- \
  "$STABLE_DART" run --enable-asserts "$PKG/../../../apps/tina_cli/bin/tina.dart" \
  --config "$CFG/config" --cwd . --no-sandbox --yolo --pipes \
  | tee "$NATIVE_OUT"

echo "=== wasm engine under wasmtime"
WASM_OUT=/tmp/stage5_wasm.txt
TINA_LLM_ENDPOINT=http://127.0.0.1:8731 TINA_LLM_TOKEN=stage5-token \
  "$DART" run --enable-asserts "$PKG/tool/pipes_drive.dart" \
  --workspace "$WS_WASM" -- \
  "$RUNNER" \
  --preopen=.="$WS_WASM" --preopen=config="$CFG" \
  --env=TINA_LLM_ENDPOINT=http://127.0.0.1:8731 \
  --env=TINA_LLM_TOKEN=stage5-token \
  | tee "$WASM_OUT"

echo "=== native RESULT lines:"
grep "RESULT" "$NATIVE_OUT" || true
echo "=== wasm RESULT lines:"
grep "RESULT" "$WASM_OUT" || true

grep -q "RESULT: PASS" "$NATIVE_OUT"
grep -q "RESULT: PASS" "$WASM_OUT"
echo "STAGE-5 EXIT TEST: both engines completed the turn"
